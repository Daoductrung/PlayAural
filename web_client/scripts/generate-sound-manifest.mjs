import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const webRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const soundsDir = path.join(webRoot, "sounds");
const outputFile = path.join(webRoot, "generated", "soundManifest.js");

function walk(directory, output = []) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      walk(fullPath, output);
    } else if (/\.(ogg|wav|mp3)$/i.test(entry.name)) {
      output.push(fullPath);
    }
  }
  return output;
}

if (!fs.existsSync(soundsDir)) {
  throw new Error(`Missing sounds directory: ${soundsDir}`);
}

const assets = walk(soundsDir)
  .map((file) => path.relative(soundsDir, file).replaceAll("\\", "/"))
  .sort();
const families = new Map();
for (const asset of assets) {
  const match = /^(.*?)([1-9][0-9]*)\.(ogg|wav|mp3)$/i.exec(asset);
  if (!match) {
    continue;
  }
  const entries = families.get(match[1]) || [];
  entries.push({ asset, index: Number(match[2]) });
  families.set(match[1], entries);
}
const lines = [
  "// Generated by scripts/generate-sound-manifest.mjs. Do not edit by hand.",
  "export const soundFamilies = Object.freeze({",
  ...[...families.entries()].sort(([left], [right]) => left.localeCompare(right)).map(
    ([family, entries]) => {
      const variants = entries
        .sort((left, right) => left.index - right.index || left.asset.localeCompare(right.asset))
        .map(({ asset }) => JSON.stringify(asset))
        .join(", ");
      return `  ${JSON.stringify(family)}: Object.freeze([${variants}]),`;
    },
  ),
  "});",
  "",
];

fs.mkdirSync(path.dirname(outputFile), { recursive: true });
fs.writeFileSync(outputFile, lines.join("\n"), "utf8");
console.log(`Scanned ${assets.length} sound assets and wrote ${outputFile}`);
